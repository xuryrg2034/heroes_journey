import { chromium } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { walkRun } from '../../../../src/realtime/run/metaWalk.testkit.ts';
import { serializeRtRun } from '../../../../src/realtime/run/rtRun.ts';

const directory = fileURLToPath(new URL('.', import.meta.url));
const base = 'http://127.0.0.1:5189/';
const profile = {
  version: 1, giftFull: false, runs: 3, won: true,
  meta: {
    heroes: {
      cat: { xp: 40, packs: [], record: { row: 9, won: true, xp: 40 } },
      toad: { xp: 5, packs: [] },
    },
    hearth: {
      stock: 60, levels: { owl: 2, herb: 2, smith: 2 },
      met: { herb: true, smith: true },
      lines: { 'owl:first': 2, 'herb:first': 2, 'smith:first': 2 }, quiet: 0,
    },
    freed: { toad: { row: 7, run: 1 } }, hero: 'toad',
  },
};

function preparedRun(k, predicate) {
  let found = null;
  walkRun({
    k, create: { gift: 'full', seeded: true, garrison: true },
    each: run => { if (!found && predicate(run)) found = structuredClone(run); },
  });
  if (!found) throw new Error(`No prepared run for seed index ${k}`);
  return found;
}

const shop = preparedRun(3, run => run.pending?.kind === 'shop' && run.talismans.length >= 6);
const reward = preparedRun(7, run => run.pending?.kind === 'talisman' && run.pending.source === 'hard' && run.talismans.length >= 7 && run.pending.options.length > 1);
const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const evidence = {
  method: 'Prepared test states generated by metaWalk.testkit; not a player playtest.',
  base,
  seeds: { shop: shop.seed, reward: reward.seed },
  states: { shop: { pending: shop.pending, talismans: shop.talismans }, reward: { pending: reward.pending, talismans: reward.talismans } },
  captures: {},
};

async function open(viewport, run = null) {
  const context = await browser.newContext({ viewport, deviceScaleFactor: 1 });
  await context.route('**/__rt-telemetry', route => route.fulfill({ status: 200, contentType: 'application/json', body: '{}' }));
  await context.addInitScript(({ profileText, runText }) => {
    localStorage.clear();
    localStorage.setItem('ashen-oath-realtime-prologue-done', '1');
    localStorage.setItem('ashen-oath-rt-profile-v1', profileText);
    if (runText) localStorage.setItem('ashen-oath-rt-run-v7', runText);
  }, { profileText: JSON.stringify(profile), runText: run ? serializeRtRun(run) : null });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto(base);
  await page.waitForFunction(() => !!window.__realtime?.run);
  return { context, page, errors };
}

async function shot(page, name) {
  await page.screenshot({ path: `${directory}${name}.png` });
  evidence.captures[name] = { viewport: page.viewportSize() };
}

try {
  for (const width of [1280, 1920]) {
    const height = width === 1280 ? 720 : 1080;
    const { context, page, errors } = await open({ width, height });
    await page.getByTestId('run-hearth').click();
    await page.getByTestId('hearth').waitFor();
    await page.waitForTimeout(250);
    await shot(page, `current-camp-${width}`);
    evidence.captures[`current-camp-${width}`].geometry = await page.evaluate(() => {
      const box = selector => { const r = document.querySelector(selector)?.getBoundingClientRect(); return r && { x: r.x, y: r.y, width: r.width, height: r.height }; };
      return {
        stage: box('[data-testid="hearth"]'), artCenterX: window.innerWidth / 2,
        backgroundArtBounds: { x: (window.innerWidth - 1280) / 2, y: (window.innerHeight - 720) / 2, width: 1280, height: 720 },
        firePanel: box('.rt-hearth-center'),
        owl: box('[data-testid="hearth-npc-owl"]'), herb: box('[data-testid="hearth-npc-herb"]'),
        cat: box('[data-testid="hearth-hero-cat"]'), toad: box('[data-testid="hearth-hero-toad"]'),
      };
    });
    if (width === 1280) {
      await page.getByTestId('hearth-npc-owl').click();
      await shot(page, 'current-npc-1280');
    }
    evidence.captures[`current-camp-${width}`].errors = errors;
    await context.close();
  }

  {
    const { context, page, errors } = await open({ width: 1280, height: 720 }, shop);
    await page.getByTestId('run-shop').waitFor();
    await shot(page, 'current-shop-1280');
    evidence.captures['current-shop-1280'].errors = errors;
    await context.close();
  }

  {
    const { context, page, errors } = await open({ width: 1280, height: 720 }, reward);
    await page.getByTestId('run-talisman').waitFor();
    await page.waitForTimeout(750);
    await shot(page, 'current-reward-1280');
    const button = page.locator('[data-testid="run-talisman"] button[data-action="talisman"][data-option]:not([data-option=""])').first();
    await button.click();
    await page.getByTestId('run-map').waitFor();
    await shot(page, 'current-dense-map-1280');
    evidence.captures['current-dense-map-1280'].geometry = await page.evaluate(() => {
      const header = document.querySelector('.rt-run-head');
      if (!header) return null;
      const h = header.getBoundingClientRect();
      const pieces = [...header.children].map(element => {
        const r = element.getBoundingClientRect();
        return {
          name: element.getAttribute('data-testid') || element.className || element.tagName,
          text: (element.textContent || '').trim().slice(0, 90),
          x: r.x, right: r.right, width: r.width, height: r.height,
          clippedRight: r.right > Math.min(h.right, window.innerWidth),
        };
      });
      return { header: { x: h.x, right: h.right, width: h.width, height: h.height, scrollWidth: header.scrollWidth, clientWidth: header.clientWidth }, pieces, overflowed: pieces.filter(piece => piece.clippedRight).map(piece => piece.name) };
    });
    evidence.captures['current-dense-map-1280'].errors = errors;
    await context.close();
  }
} finally {
  await browser.close();
  await writeFile(`${directory}dense-evidence.json`, JSON.stringify(evidence, null, 2) + '\n');
}
